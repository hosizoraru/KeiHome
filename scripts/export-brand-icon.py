#!/usr/bin/env python3
"""Export the SVG master to Android vectors and a compact visual proof sheet."""
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
BRANDING = ROOT / "docs/branding"
RES = ROOT / "app/src/main/res"
SVG_NS = "{http://www.w3.org/2000/svg}"


def main():
    master = ET.parse(BRANDING / "keihome-icon.svg").getroot()
    paths = list(master.iter(f"{SVG_NS}path"))
    light = {c.attrib["name"]: c.text for c in ET.parse(RES / "values/colors.xml").getroot()}
    dark = light | {
        c.attrib["name"]: c.text for c in ET.parse(RES / "values-night/colors.xml").getroot()
    }
    for path in paths:
        if path.attrib["fill"] != light[path.attrib["data-color"]]:
            raise ValueError(f"SVG/Android palette mismatch: {path.attrib['id']}")

    header = (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by scripts/export-brand-icon.py from docs/branding/keihome-icon.svg. -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="108dp" android:height="108dp"\n'
        '    android:viewportWidth="108" android:viewportHeight="108">\n'
    )
    for mode in ("foreground", "monochrome"):
        lines = []
        for path in paths:
            color = path.attrib["data-color"] if mode == "foreground" else "ic_launcher_monochrome"
            lines.append(
                f'    <path android:fillColor="@color/{color}"\n'
                f'        android:pathData="{path.attrib["d"]}" />\n'
            )
        (RES / f"drawable/ic_launcher_{mode}.xml").write_text(header + "".join(lines) + "</vector>\n")

    def mark(palette, tint=None):
        return "".join(
            f'<path fill="{tint or palette[p.attrib["data-color"]]}" d="{p.attrib["d"]}"/>'
            for p in paths
        )

    def svg(body, width=108, height=108):
        return (
            f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
            f'viewBox="0 0 {width} {height}">{body}</svg>\n'
        )

    exports = BRANDING / "exports"
    exports.mkdir(exist_ok=True)
    for name, palette in (("light", light), ("dark", dark)):
        body = f'<path fill="{palette["ic_launcher_background"]}" d="M0,0H108V108H0Z"/>'
        (exports / f"keihome-{name}.svg").write_text(svg(body + mark(palette)))
    (exports / "keihome-monochrome.svg").write_text(svg(mark(light, "#000000")))

    # Preview the visible 72dp crop, not the entire 108dp adaptive layer.
    masks = {
        "squircle": "M18,0H54C67,0 72,5 72,18V54C72,67 67,72 54,72H18C5,72 0,67 0,54V18C0,5 5,0 18,0Z",
        "circle": "M72,36A36,36 0 1,1 0,36A36,36 0 1,1 72,36Z",
        "rounded": "M14,0H58Q72,0 72,14V58Q72,72 58,72H14Q0,72 0,58V14Q0,0 14,0Z",
    }
    defs = "<defs>" + "".join(
        f'<clipPath id="{name}"><path d="{data}"/></clipPath>' for name, data in masks.items()
    ) + "</defs>"

    def tile(x, y, size, palette, shape="squircle", tint=None, background=None):
        bg = background or palette["ic_launcher_background"]
        return (
            f'<g transform="translate({x},{y}) scale({size / 72})" clip-path="url(#{shape})">'
            f'<path fill="{bg}" d="M0,0H72V72H0Z"/>'
            f'<g transform="translate(-18,-18)">{mark(palette, tint)}</g></g>'
        )

    def text(x, y, content, size=17, fill="#5A6665"):
        return f'<text x="{x}" y="{y}" font-family="sans-serif" font-size="{size}" fill="{fill}">{content}</text>'

    body = defs + '<path fill="#F7F8F5" d="M0,0H1200V780H0Z"/>'
    body += text(56, 62, "KeiHome / A home for icons", 30, "#173D42")
    body += text(56, 96, "Your home screen. Your icons. Your colors.")
    variants = [
        ("LIGHT", light, None, None),
        ("DARK", dark, None, None),
        ("MONET / LIGHT", light, "#174E45", "#C6EADB"),
        ("MONET / DARK", dark, "#ADEEDB", "#234F48"),
    ]
    for column, (label, palette, tint, bg) in enumerate(variants):
        x = 56 + column * 286
        body += tile(x, 134, 228, palette, tint=tint, background=bg)
        body += text(x, 396, label)
        body += tile(x, 422, 96, palette, "circle", tint, bg)
        body += tile(x + 122, 422, 96, palette, "rounded", tint, bg)
        body += tile(x, 561, 48, palette, tint=tint, background=bg)
        body += tile(x + 72, 573, 24, palette, tint=tint, background=bg)
        body += text(x, 647, "48px / 24px", 14)
    body += text(56, 716, "Adaptive layer: 108dp / Visible mask: 72dp / No baked-in icon container", 16)
    body += text(56, 745, "Monet colors here are illustrative. The launcher supplies the actual tint.", 14)
    (BRANDING / "preview.svg").write_text(svg(body, 1200, 780))
    print("Exported foreground, monochrome, three SVG variants and preview.svg")


if __name__ == "__main__":
    main()
