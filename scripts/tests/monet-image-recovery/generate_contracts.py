"""Offline structural contracts; symbols are an oracle, never a runtime lookup."""
import argparse
import hashlib
import importlib.util
import json
from pathlib import Path
import struct
import sys
sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location('trace_contracts', HERE.parent/'monet-image-trace/generate_contracts.py')
trace = importlib.util.module_from_spec(spec)
spec.loader.exec_module(trace)
Fixture = trace.Fixture
ROLES = [('Clone', 'Image.clone'), ('Dispose', 'Image.dispose'),
         ('RawUpdate', 'RawImage.updateRenderObject'), ('RawCreate', 'RawImage.createRenderObject'),
         ('RenderSet', 'RenderImage.image='), ('RenderDispose', 'RenderImage.dispose'),
         ('GuardedClone', 'UninstallAppHelper._buildShortCutDoBoomAnim')]


def normalize(words, role):
    out = trace.normalize(words, role)
    if role == 'RawUpdate':
        assert words[15] & 0xffe0001f == 0xd2800011
        out[15] &= 0xffe0001f  # RenderImage CID independently tied to allocator
    if role == 'GuardedClone':
        assert words[0xb8//4] & 0xffe0001f == 0xd2800011
        out[0xb8//4] &= 0xffe0001f  # Image CID tied to clone allocator and cast
    return out


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--library', type=Path, action='append', required=True)
    p.add_argument('--output', type=Path, required=True)
    p.add_argument('--evidence', type=Path, required=True)
    a = p.parse_args()
    patterns, evidence = [], []
    for path in a.library:
        f = Fixture(path)
        row = {'library': str(f.path), 'sha256': hashlib.sha256(f.data).hexdigest(), 'roles': {}}
        for role, name in ROLES:
            pc, size = f.role(name)
            if role == 'GuardedClone': size = 0x100
            assert 16 <= size <= 2048 and size % 4 == 0
            words = struct.unpack('<'+'I'*(size//4), f.read(pc, size))
            normalized = normalize(words, role)
            digest = hashlib.sha256(struct.pack('<'+'I'*len(words), *normalized)).digest()
            shape = (role, len(words), tuple(normalized[:4]), digest)
            if shape not in patterns: patterns.append(shape)
            row['roles'][role] = {'rva': pc, 'size': size}
        evidence.append(row)
    order = {r: i for i, (r, _) in enumerate(ROLES)}
    lines = ['// SPDX-License-Identifier: Apache-2.0',
             '// Generated by scripts/tests/monet-image-recovery/generate_contracts.py.',
             '// Instruction families only; no launcher RVAs or whole-ELF allowlist.',
             'enum Role { '+', '.join('k'+r for r, _ in ROLES)+', kRoleCount };',
             'constexpr Pattern kPatterns[] = {']
    for role, count, prefix, digest in sorted(patterns, key=lambda x: (order[x[0]], x[1], x[3])):
        lines.append('    {k%s, %d, {%s},\n     {%s}},' % (role, count,
            ', '.join(f'0x{w:08x}u' for w in prefix), ', '.join(f'0x{b:02x}' for b in digest)))
    lines.append('};\n')
    a.output.write_text('\n'.join(lines))
    a.evidence.write_text(json.dumps(evidence, indent=2)+'\n')
    print(f'{len(patterns)} recovery shapes across {len(evidence)} external ELFs')


if __name__ == '__main__': main()
