#!/usr/bin/env python3
"""Host oracle: derive the bounded normal ZIP destructor graph from miniDebugdata.

Requires pyelftools and capstone. No addresses, hashes or symbol names are used
by the generated runtime matcher. Both supplied images must produce one graph.
"""
import io
import lzma
import struct
import sys
from pathlib import Path

from capstone import Cs, CS_ARCH_ARM64, CS_MODE_LITTLE_ENDIAN
from elftools.elf.elffile import ELFFile


def graph(path):
    with open(path, "rb") as stream:
        elf = ELFFile(stream)
        debug = ELFFile(io.BytesIO(lzma.decompress(
            elf.get_section_by_name(".gnu_debugdata").data())))
        symbols = {s["st_value"]: (s["st_size"], s.name)
                   for s in debug.get_section_by_name(".symtab").iter_symbols()
                   if s["st_info"]["type"] == "STT_FUNC" and s["st_size"]}
        roots = [a for a, (_, n) in symbols.items()
                 if "zip_archive6SharedE9drop_slow" in n]
        assert len(roots) == 1
        plt = elf.get_section_by_name(".plt")
        assert plt is not None

        def read(address, length):
            for segment in elf.iter_segments():
                if (segment["p_type"] == "PT_LOAD"
                        and segment["p_vaddr"] <= address
                        and address + length <= segment["p_vaddr"] + segment["p_filesz"]):
                    offset = address - segment["p_vaddr"]
                    return segment.data()[offset:offset + length]
            raise ValueError(f"unmapped address {address:#x}")

        addresses, nodes, labels = [roots[0]], [], []
        md = Cs(CS_ARCH_ARM64, CS_MODE_LITTLE_ENDIAN)
        for address in addresses:
            if plt["sh_addr"] <= address < plt["sh_addr"] + plt["sh_size"]:
                # Runtime checks the PLT instructions, relocation, UND free
                # symbol and libc dependency, not this oracle's RVA.
                nodes.append((16, []))
                labels.append("allocator PLT (runtime-authenticated free)")
                continue
            size, name = symbols[address]
            assert size <= 256
            instructions = {i.address: i for i in md.disasm(read(address, size), address)}
            pending, visited = [address], set()
            while pending:
                pc = pending.pop()
                if pc in visited:
                    continue
                visited.add(pc)
                ins = instructions[pc]
                assert ins.mnemonic not in ("br", "blr", "adr", "adrp")
                branch = (ins.mnemonic in ("b", "bl", "cbz", "cbnz", "tbz", "tbnz")
                          or ins.mnemonic.startswith("b."))
                target = int(ins.op_str.split(",")[-1].strip()[1:], 0) if branch else None
                if target is not None and address <= target < address + size:
                    pending.append(target)
                elif target is not None:
                    assert ins.mnemonic in ("b", "bl")
                if ins.mnemonic not in ("b", "ret"):
                    pending.append(pc + 4)
            words = []
            for pc in sorted(visited):
                ins = instructions[pc]
                word = struct.unpack("<I", ins.bytes)[0]
                link = -1
                if ins.mnemonic in ("b", "bl"):
                    target = int(ins.op_str[1:], 0)
                    if not address <= target < address + size:
                        if target not in addresses:
                            addresses.append(target)
                        link = addresses.index(target)
                        word &= 0xfc000000
                words.append((pc - address, word, link))
            nodes.append((size, words))
            labels.append(name)
        assert len(nodes) == 37 and sum(len(w) for _, w in nodes) == 238
        return nodes, labels


def main():
    assert len(sys.argv) == 4, "generator SDK1 SDK2 output.inc"
    first, labels = graph(sys.argv[1])
    second, _ = graph(sys.argv[2])
    assert first == second, "SDK normal destructor graphs differ"
    lines = [
        "// SPDX-License-Identifier: Apache-2.0",
        "// Generated by scripts/tests/maml-zip-release/generate_patterns.py from BOTH SDK oracles.",
        "// Only normal reachable instructions; exception landing pads are excluded.",
        "struct ZipWord { uint16_t offset; uint32_t word; int16_t target; };",
        "struct ZipNode { uint16_t first, count, span; };",
        "constexpr ZipWord kZipWords[] = {",
    ]
    for index, ((_, words), label) in enumerate(zip(first, labels)):
        lines.append(f"    // Node {index}: {label}")
        for offset, word, target in words:
            lines.append(f"    {{{offset}, 0x{word:08x}u, {target}}},")
    lines.append("};\nconstexpr ZipNode kZipNodes[] = {")
    cursor = 0
    for span, words in first:
        lines.append(f"    {{{cursor}, {len(words)}, {span}}},")
        cursor += len(words)
    lines.append("};\n")
    Path(sys.argv[3]).write_text("\n".join(lines), encoding="ascii")


if __name__ == "__main__":
    main()
