"""Generate diagnostic ABI fingerprints from external launcher ELFs only.

The bundled .gnu_debugdata is an offline oracle, never a runtime dependency.
No extracted function bodies or library RVAs are emitted into production data.
"""
import argparse
import hashlib
import io
import json
import lzma
from pathlib import Path
import struct
import sys
sys.dont_write_bytecode = True
from elftools.elf.elffile import ELFFile

ROLES = [
    ("Dispose", "Image.dispose"), ("Clone", "Image.clone"),
    ("Build", "_MonochromeIconWidgetState.build"),
    ("Clear", "MonochromeIconCache.clear"), ("Put", "MonochromeIconCache.put"),
    ("RawUpdate", "RawImage.updateRenderObject"),
    ("Unmount", "StatefulElement.unmount"),
]


def normalize(words, role):
    """Only external BLs, PP indices and the decoded GDT selector relocate.

    All frame/register/object-field/local-control-flow instructions stay exact.
    Different bodies (e.g. the older clear loop) get distinct fingerprints.
    """
    out = list(words)
    for i, w in enumerate(words):
        if w & 0xfc000000 == 0x94000000:
            out[i] = w & 0xfc000000
        if w & 0xffc003e0 == 0x91400360 and i + 1 < len(words):
            nxt = words[i+1]
            if nxt & 0xffc003e0 == 0xf9400000 | (w & 31) << 5:
                out[i] = w & ~0x003ffc00
                out[i+1] = nxt & ~0x003ffc00
        if w & 0xffc003e0 == 0xf9400360 and (w >> 10 & 4095)*8 >= 256:
            out[i] = w & ~0x003ffc00
        if role == "Unmount" and i == 13:
            assert w & 0xffe0001f == 0xd2800011
            out[i] = w & 0xffe0001f
    return out


class Fixture:
    def __init__(self, path):
        self.path = Path(path).resolve()
        self.data = self.path.read_bytes()
        self.elf = ELFFile(io.BytesIO(self.data))
        assert self.elf['e_machine'] == 'EM_AARCH64'
        self.segments = [(s['p_vaddr'], s.data()) for s in self.elf.iter_segments()
                         if s['p_type'] == 'PT_LOAD']
        debug = ELFFile(io.BytesIO(lzma.decompress(self.elf.get_section_by_name('.gnu_debugdata').data())))
        self.symbols = {}
        for s in debug.get_section_by_name('.symtab').iter_symbols():
            if s['st_size']:
                self.symbols.setdefault(s.name, []).append((s['st_value'], s['st_size']))

    def read(self, pc, size):
        for start, data in self.segments:
            if start <= pc and pc + size <= start + len(data):
                return data[pc-start:pc-start+size]
        raise ValueError(f'unmapped {pc:x}+{size:x}')

    def role(self, name):
        matches = self.symbols[name]
        assert len(matches) == 1, (name, matches)
        return matches[0]


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--library', type=Path, action='append', required=True)
    p.add_argument('--output', type=Path, required=True)
    p.add_argument('--evidence', type=Path, required=True)
    a = p.parse_args()
    patterns, evidence = [], []
    for library in a.library:
        f = Fixture(library)
        row = {'library': str(f.path), 'sha256': hashlib.sha256(f.data).hexdigest(), 'roles': {}}
        for role, name in ROLES:
            pc, size = f.role(name)
            assert 16 <= size <= 2048 and size % 4 == 0
            words = list(struct.unpack('<'+'I'*(size//4), f.read(pc, size)))
            normalized = normalize(words, role)
            digest = hashlib.sha256(struct.pack('<'+'I'*len(words), *normalized)).digest()
            # Every normalized BL must still resolve into executable code at runtime.
            calls = []
            for i, w in enumerate(words):
                if w & 0xfc000000 == 0x94000000:
                    target = pc+4*i+(((w & 0x3ffffff)^0x2000000)-0x2000000)*4
                    calls.append({'offset': i*4, 'target': target})
            row['roles'][role] = {'rva': pc, 'size': size, 'calls': calls}
            entry = (role, len(words), tuple(normalized[:4]), digest)
            if entry not in patterns:
                patterns.append(entry)
        evidence.append(row)
    lines = ['// SPDX-License-Identifier: Apache-2.0',
             '// Generated by scripts/tests/monet-image-trace/generate_contracts.py.',
             '// Structural fingerprints only; no launcher RVAs or image allowlist.',
             'enum Role { '+', '.join('k'+r for r, _ in ROLES)+', kRoleCount };',
             'constexpr Pattern kPatterns[] = {']
    role_order = {role: index for index, (role, _) in enumerate(ROLES)}
    for role, count, prefix, digest in sorted(patterns, key=lambda p: (role_order[p[0]], p[1], p[3])):
        lines.append('    {k%s, %d, {%s},\n     {%s}},' % (
            role, count, ', '.join(f'0x{w:08x}u' for w in prefix),
            ', '.join(f'0x{b:02x}' for b in digest)))
    lines.append('};\n')
    a.output.write_text('\n'.join(lines))
    a.evidence.write_text(json.dumps(evidence, indent=2)+'\n')
    print(f'{len(patterns)} code shapes across {len(evidence)} external images')


if __name__ == '__main__':
    main()
