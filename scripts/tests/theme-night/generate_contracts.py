"""Offline code-family fingerprints. External symbols are a test oracle only."""
import argparse
import hashlib
import importlib.util
import json
from pathlib import Path
import struct
import sys

sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location(
    "trace_contracts", HERE.parent / "monet-image-trace/generate_contracts.py")
trace = importlib.util.module_from_spec(spec)
spec.loader.exec_module(trace)
Fixture = trace.Fixture
ROLES = [
    ("Init", "ThemeResourcesSystem._initIconTheme"),
    ("Create", "ThemeResourcesSystem._createChain"),
    ("Seed", "ThemeResourcesSystem._seedInitialNightMode"),
    ("ReadMode", "ThemeChangeSignals.readInitialNightMode"),
    ("SystemSetter", "ThemeResourcesSystem.setNightModeEnable"),
    ("NodeSetter", "ThemeResources.setNightModeEnable"),
    ("Apply", "ThemeResourcesSystem.applyNightMode"),
    ("SystemBitmap", "ThemeResourcesSystem.getIconBitmap"),
    ("NodeBitmap", "ThemeResources.getIconBitmap"),
    ("BitmapLocal", "ThemeResources._getIconBitmapLocal"),
    ("GetSystem", "ThemeResourcesSystem.getSystem"),
    ("Stream", "ThemeResources.getFileStream"),
    ("HasFile", "ThemeResources.hasFile"),
    ("StringEquals", "String.=="),
]
FIELDS = {"Create": (0x17c,), "NodeSetter": (8, 0x2c),
          "BitmapLocal": (0xa4,), "Stream": (0x34,), "HasFile": (0x30,)}


def role(fixture, name):
    matches = fixture.symbols[name]
    if name == "String.==":
        # One-byte comparison untags length (ASR #1), then divides by eight.
        # The two-byte routine omits the first shift; size alone is no oracle.
        matches = [(pc, size) for pc, size in matches if size == 0xb0 and
                   struct.unpack("<I", fixture.read(pc+0x34, 4))[0] == 0x9341fc42]
    assert len(matches) == 1, (name, matches)
    return matches[0]


def normalize(words, name):
    out = list(words)
    for i, w in enumerate(words):
        if w & 0xfc000000 == 0x94000000:
            out[i] &= 0xfc000000
        if w & 0xfc000000 == 0x14000000:
            target = i + (((w & 0x3ffffff) ^ 0x2000000) - 0x2000000)
            if not 0 <= target < len(words):
                out[i] &= 0xfc000000
        if w & 0xffc003e0 == 0x91400360 and i+1 < len(words):
            nxt = words[i+1]
            if nxt & 0xffc003e0 == 0xf9400000 | (w & 31) << 5:
                out[i] &= ~0x003ffc00
                out[i+1] &= ~0x003ffc00
        if w & 0xffc003e0 == 0xf9400360:
            out[i] &= ~0x003ffc00
        if w & 0xffc003e0 == 0xf9400340 and i+1 < len(words):
            nxt = words[i+1]
            if nxt & 0xff8003e0 == 0xf9000000 | (w & 31) << 5:
                out[i] &= ~0x003ffc00
                out[i+1] &= ~0x003ffc00
        if i*4 in FIELDS.get(name, ()):
            out[i] &= ~0x001ff000
        if name == "NodeSetter" and i*4 == 0x24:
            out[i] &= ~0x003ffc00
    return out


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--library", type=Path, action="append", required=True)
    p.add_argument("--output", type=Path, required=True)
    p.add_argument("--evidence", type=Path, required=True)
    args = p.parse_args()
    assert __debug__
    patterns, evidence = [], []
    for path in args.library:
        f = Fixture(path)
        row = {"library": str(f.path), "sha256": hashlib.sha256(f.data).hexdigest(), "roles": {}}
        for key, name in ROLES:
            pc, size = role(f, name)
            assert 16 <= size <= 2048 and size % 4 == 0
            words = struct.unpack("<" + "I"*(size//4), f.read(pc, size))
            normalized = normalize(words, key)
            digest = hashlib.sha256(struct.pack("<" + "I"*len(words), *normalized)).digest()
            shape = (key, len(words), tuple(normalized[:4]), digest)
            if shape not in patterns:
                patterns.append(shape)
            row["roles"][key] = {"rva": pc, "size": size}
        evidence.append(row)
    order = {key: i for i, (key, _) in enumerate(ROLES)}
    lines = ["// SPDX-License-Identifier: Apache-2.0",
             "// Generated by scripts/tests/theme-night/generate_contracts.py.",
             "// Normalized code-family digests; no version RVAs or image hashes.",
             "enum Role { " + ", ".join("k"+key for key, _ in ROLES) + ", kRoleCount };",
             "constexpr Pattern kPatterns[] = {"]
    for key, count, prefix, digest in sorted(patterns, key=lambda s: (order[s[0]], s[3])):
        lines.append("    {k%s, %d, {%s},\n     {%s}}," % (
            key, count, ", ".join(f"0x{w:08x}u" for w in prefix),
            ", ".join(f"0x{b:02x}" for b in digest)))
    lines.append("};\n")
    args.output.write_text("\n".join(lines))
    args.evidence.write_text(json.dumps(evidence, indent=2) + "\n")
    print(f"{len(patterns)} theme-night shapes across {len(evidence)} external images")


if __name__ == "__main__":
    main()
